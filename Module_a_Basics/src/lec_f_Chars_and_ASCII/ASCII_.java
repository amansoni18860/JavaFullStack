package lec_f_Chars_and_ASCII;

public class ASCII_ {

	public static void main(String[] args) {

		for(int i=65;i<=90;i++) {
			System.out.print(i+"-"+(char)i+" ");
		}
		System.out.println();
		System.out.println();

		
		for(int i=97;i<=122;i++) {
			System.out.print(i+"-"+(char)i+" ");
		}
		
		System.out.println();
		System.out.println();

		for(int i=48;i<=57;i++) {
			System.out.print(i+"-"+(char)i+" ");
		}
		
		
		System.out.println();
		System.out.println();
		
		
		for(int i=0;i<=127;i++) {
			System.out.print(i+"-"+(char)i+" ");
		}
		

	}

}
